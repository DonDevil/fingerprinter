"""Generate a seeded **synthetic** corpus (ffmpeg test sources) with a manifest.

Used for harness validation and synthetic benchmarks only. It is never a
substitute for the licensed real-media corpora (S-SRC, C-PREC, L-PAIRS,
SOAK-1000; data-preparation §2) and reports built on it say so.

    env/bin/python benchmarks/p9-encoder/make_synthetic_corpus.py \
        --out ~/anti_piracy/datasets/p9/synthetic-mini --count 60 --seed 7
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import subprocess
from datetime import UTC, datetime
from pathlib import Path

CODECS = [
    ("mp4", ["-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p"]),
    ("mkv", ["-c:v", "libx265", "-preset", "ultrafast", "-pix_fmt", "yuv420p", "-x265-params", "log-level=error"]),
    ("webm", ["-c:v", "libvpx-vp9", "-deadline", "realtime", "-cpu-used", "8", "-pix_fmt", "yuv420p"]),
    ("mkv", ["-c:v", "libsvtav1", "-preset", "12", "-pix_fmt", "yuv420p"]),
]
SOURCES = ["testsrc2", "testsrc", "smptehdbars", "life", "rgbtestsrc", "cellauto", "yuvtestsrc"]
SIZES = ["320x240", "426x240", "640x360", "854x480", "1280x720"]
RATES = [24, 25, 30, 60]


def _ff(args: list[str]) -> None:
    subprocess.run(["ffmpeg", "-nostdin", "-loglevel", "error", "-y", *args], check=True)  # noqa: S603, S607


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--count", type=int, default=60)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--max-seconds", type=float, default=90.0)
    ap.add_argument("--corrupt", type=int, default=4)
    ap.add_argument("--audio-only", type=int, default=2)
    args = ap.parse_args()
    rng = random.Random(args.seed)
    out = args.out.expanduser()
    out.mkdir(parents=True, exist_ok=True)
    items = []
    for i in range(args.count):
        ext, codec = rng.choice(CODECS)
        src, size, rate = rng.choice(SOURCES), rng.choice(SIZES), rng.choice(RATES)
        seconds = round(rng.uniform(6, args.max_seconds), 1)
        name = f"syn-{i:04d}.{ext}"
        lavfi = f"{src}=size={size}:rate={rate}"
        vf = [f"hue=h={rng.randint(0, 359)}"]
        if i % 10 == 3:  # variable frame rate
            vf.append("setpts='N/FRAME_RATE/TB+if(gt(N,30),0.5/TB,0)'")
        extra = ["-t", str(seconds)]
        vf.append("format=yuv420p")
        _ff(["-f", "lavfi", "-i", lavfi, *extra, "-vf", ",".join(vf), "-fps_mode", "passthrough", *codec,
             "-an", str(out / name)])
        items.append({"file": name, "kind": "video", "codec": codec[1], "size": size, "fps": rate,
                      "seconds": seconds, "source": f"ffmpeg lavfi {src}", "expect": "READY"})
    for j in range(args.corrupt):
        good = out / items[j]["file"]
        name = f"corrupt-{j:02d}{good.suffix}"
        data = good.read_bytes()
        bad = data[: len(data) // 3] if j % 2 == 0 else data[:64] + bytes(rng.randrange(256) for _ in range(4096))
        (out / name).write_bytes(bad)
        items.append({"file": name, "kind": "corrupt", "expect": "FAILED:decode_error|unsupported_format"})
    for k in range(args.audio_only):
        name = f"audio-{k:02d}.m4a"
        _ff(["-f", "lavfi", "-i", f"sine=frequency={300 + 100 * k}:duration=5", "-c:a", "aac", str(out / name)])
        items.append({"file": name, "kind": "audio_only", "expect": "FAILED:unsupported_format"})
    for it in items:
        data = (out / it["file"]).read_bytes()
        it["sha256"] = hashlib.sha256(data).hexdigest()
        it["bytes"] = len(data)
    manifest = {
        "corpus": f"synthetic-{args.count}-seed{args.seed}",
        "synthetic": True,
        "licence": "generated by ffmpeg lavfi test sources (no third-party content)",
        "created_at": datetime.now(UTC).isoformat(),
        "generator": "benchmarks/p9-encoder/make_synthetic_corpus.py",
        "args": {k: str(v) for k, v in vars(args).items()},
        "items": items,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    print(json.dumps({"out": str(out), "items": len(items)}))


if __name__ == "__main__":
    main()
